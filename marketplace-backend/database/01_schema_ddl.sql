-- =============================================================================
-- Marketplace - 01_schema_ddl.sql
-- Esquema completo para PostgreSQL 13 o superior, desde una base de datos vacía.
--
-- Nombres: los genera la estrategia por defecto de Spring Boot a partir de las
-- entidades JPA (configuracionTarifa -> configuracion_tarifa, precioNoche ->
-- precio_noche). No cambiarlos sin cambiar las entidades.
--
-- Reglas de integridad referencial:
--   ON UPDATE RESTRICT en todas: las claves son IDENTITY y nunca cambian.
--   ON DELETE CASCADE  solo en datos que no tienen sentido sin su dueño y no son
--                      históricos (amenidades, servicios, periodos, favoritos,
--                      notificaciones, registros de idempotencia).
--   ON DELETE SET NULL en cotizacion.id_reserva (la cotización sobrevive).
--   ON DELETE RESTRICT en lo demás: reservas, pagos, cancelaciones, reseñas e
--                      historial son registros de negocio que no se pierden.
--
-- NOT NULL: una columna solo lo lleva si todos los flujos del backend la llenan.
-- Por eso los borradores de alojamiento admiten casi todo en NULL, y
-- usuario.totp_habilitado admite NULL (AdminInicializador no lo asigna).
-- Hibernate envía NULL explícito en los INSERT, así que un DEFAULT no lo evitaría.
-- =============================================================================
SET client_encoding = 'UTF8';

-- Necesaria para las restricciones EXCLUDE que combinan BIGINT (=) con rangos (&&).
-- Es una extensión "trusted" desde PostgreSQL 13: basta con ser dueño de la base.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- -----------------------------------------------------------------------------
-- Usuarios
-- -----------------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre              VARCHAR(255)  NOT NULL,
    -- Correo cifrado con AES-GCM en Base64 (AESUtil.encrypt); cada cifrado es distinto.
    correo              VARCHAR(1024) NOT NULL,
    -- HMAC-SHA256 del correo normalizado: es lo que permite buscar por correo.
    correo_hash         VARCHAR(64)   NOT NULL,
    telefono            VARCHAR(255),
    rol                 VARCHAR(20)   NOT NULL,
    estado              VARCHAR(20)   NOT NULL DEFAULT 'ACTIVO',
    -- Hash BCrypt.
    contrasenia         VARCHAR(100)  NOT NULL,
    motivo_restriccion  VARCHAR(500),
    secreto_totp        VARCHAR(512),
    totp_habilitado     BOOLEAN                DEFAULT FALSE,
    fecha_registro      TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    correo_verificado   BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_correo_hash UNIQUE (correo_hash),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMIN', 'HUESPED', 'ANFITRION')),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO', 'INACTIVO', 'RESTRINGIDO')),
    CONSTRAINT ck_usuario_nombre CHECK (LENGTH(TRIM(nombre)) > 0),
    CONSTRAINT ck_usuario_restriccion CHECK (estado <> 'RESTRINGIDO' OR motivo_restriccion IS NOT NULL),
    CONSTRAINT ck_usuario_totp CHECK (totp_habilitado IS NOT TRUE OR secreto_totp IS NOT NULL)
);

-- -----------------------------------------------------------------------------
-- Catálogos de configuración
-- -----------------------------------------------------------------------------
CREATE TABLE politica_cancelacion (
    id_politica             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre                  VARCHAR(50)  NOT NULL,
    condiciones             VARCHAR(500) NOT NULL,
    dias_reembolso_total    INTEGER,
    dias_reembolso_parcial  INTEGER,
    porcentaje_parcial      INTEGER,
    CONSTRAINT pk_politica_cancelacion PRIMARY KEY (id_politica),
    CONSTRAINT uq_politica_nombre UNIQUE (nombre),
    CONSTRAINT ck_politica_dias CHECK (
        (dias_reembolso_total IS NULL OR dias_reembolso_total >= 0)
        AND (dias_reembolso_parcial IS NULL OR dias_reembolso_parcial >= 0)),
    CONSTRAINT ck_politica_porcentaje CHECK (
        porcentaje_parcial IS NULL OR porcentaje_parcial BETWEEN 0 AND 100),
    -- Un plazo parcial y su porcentaje van siempre juntos.
    CONSTRAINT ck_politica_parcial CHECK (
        (dias_reembolso_parcial IS NULL) = (porcentaje_parcial IS NULL))
);

CREATE TABLE configuracion_tarifa (
    id_configuracion     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    porcentaje_limpieza  NUMERIC(5, 2) NOT NULL,
    porcentaje_servicio  NUMERIC(5, 2) NOT NULL,
    id_usuario           BIGINT        NOT NULL,
    fecha                TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_configuracion_tarifa PRIMARY KEY (id_configuracion),
    CONSTRAINT fk_configuracion_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_configuracion_porcentajes CHECK (
        porcentaje_limpieza BETWEEN 0 AND 100 AND porcentaje_servicio BETWEEN 0 AND 100)
);

-- -----------------------------------------------------------------------------
-- Alojamientos
-- -----------------------------------------------------------------------------
CREATE TABLE alojamiento (
    id_alojamiento       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    titulo               VARCHAR(255)  NOT NULL,
    descripcion          VARCHAR(2000),
    ubicacion            VARCHAR(255),
    ciudad               VARCHAR(255),
    latitud              DOUBLE PRECISION,
    longitud             DOUBLE PRECISION,
    tipo                 VARCHAR(255),
    capacidad            INTEGER,
    habitaciones         INTEGER,
    camas                INTEGER,
    banos                INTEGER,
    hora_entrada         TIME,
    hora_salida          TIME,
    precio_noche         NUMERIC(12, 2),
    -- NULL significa "usar la tarifa global vigente" (configuracion_tarifa).
    porcentaje_limpieza  NUMERIC(5, 2),
    porcentaje_servicio  NUMERIC(5, 2),
    reglas               VARCHAR(2000),
    estado               VARCHAR(20)   NOT NULL DEFAULT 'BORRADOR',
    id_anfitrion         BIGINT        NOT NULL,
    id_politica          BIGINT,
    fecha_creacion       TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    fecha_actualizacion  TIMESTAMP(6),
    CONSTRAINT pk_alojamiento PRIMARY KEY (id_alojamiento),
    -- Destino de la FK compuesta de conversacion.
    CONSTRAINT uq_alojamiento_anfitrion UNIQUE (id_alojamiento, id_anfitrion),
    CONSTRAINT fk_alojamiento_anfitrion FOREIGN KEY (id_anfitrion)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_alojamiento_politica FOREIGN KEY (id_politica)
        REFERENCES politica_cancelacion (id_politica) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_alojamiento_estado CHECK (
        estado IN ('BORRADOR', 'PENDIENTE_REVISION', 'ACTIVA', 'PAUSADA', 'BLOQUEADA')),
    CONSTRAINT ck_alojamiento_titulo CHECK (LENGTH(TRIM(titulo)) > 0),
    CONSTRAINT ck_alojamiento_capacidad CHECK (capacidad IS NULL OR capacidad > 0),
    CONSTRAINT ck_alojamiento_espacios CHECK (
        (habitaciones IS NULL OR habitaciones >= 0)
        AND (camas IS NULL OR camas >= 0)
        AND (banos IS NULL OR banos >= 0)),
    CONSTRAINT ck_alojamiento_precio CHECK (
        precio_noche IS NULL OR (precio_noche > 0 AND precio_noche <= 1000000000)),
    CONSTRAINT ck_alojamiento_porcentajes CHECK (
        (porcentaje_limpieza IS NULL OR porcentaje_limpieza BETWEEN 0 AND 100)
        AND (porcentaje_servicio IS NULL OR porcentaje_servicio BETWEEN 0 AND 100)),
    CONSTRAINT ck_alojamiento_coordenadas CHECK (
        (latitud IS NULL OR latitud BETWEEN -90 AND 90)
        AND (longitud IS NULL OR longitud BETWEEN -180 AND 180)),
    -- Lo mínimo sin lo cual no se puede cotizar ni aplicar la política de una publicación activa.
    CONSTRAINT ck_alojamiento_activa_completa CHECK (
        estado <> 'ACTIVA'
        OR (capacidad IS NOT NULL AND precio_noche IS NOT NULL AND id_politica IS NOT NULL))
);

