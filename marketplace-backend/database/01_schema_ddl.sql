-- -----------------------------------------------------------------------------
-- Auditoría, exportaciones e idempotencia
-- -----------------------------------------------------------------------------
-- Inmutable. id_usuario e id_entidad NO son FK a propósito: la entidad no los
-- relaciona y la auditoría debe conservarse aunque el recurso ya no exista.
CREATE TABLE evento_auditoria (
    id_evento   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    accion      VARCHAR(50)   NOT NULL,
    fecha       TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    detalle     VARCHAR(1000),
    id_usuario  BIGINT,
    entidad     VARCHAR(50),
    id_entidad  BIGINT,
    resultado   VARCHAR(20)   NOT NULL,
    CONSTRAINT pk_evento_auditoria PRIMARY KEY (id_evento),
    CONSTRAINT ck_evento_resultado CHECK (resultado IN ('EXITOSO', 'RECHAZADO', 'ERROR'))
);

CREATE TABLE registro_exportacion (
    id_registro         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo_reporte        VARCHAR(50)  NOT NULL,
    formato             VARCHAR(10)  NOT NULL,
    cantidad_registros  INTEGER      NOT NULL,
    id_usuario          BIGINT       NOT NULL,
    fecha               TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_registro_exportacion PRIMARY KEY (id_registro),
    CONSTRAINT fk_exportacion_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_exportacion_formato CHECK (formato IN ('pdf', 'excel')),
    CONSTRAINT ck_exportacion_cantidad CHECK (cantidad_registros >= 0)
);

CREATE TABLE registro_idempotencia (
    id_registro       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    clave             VARCHAR(100) NOT NULL,
    id_usuario        BIGINT       NOT NULL,
    operacion         VARCHAR(50)  NOT NULL,
    huella_peticion   VARCHAR(64)  NOT NULL,
    estado            VARCHAR(20)  NOT NULL,
    codigo_respuesta  INTEGER,
    cuerpo_respuesta  TEXT,
    fecha_creacion    TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_registro_idempotencia PRIMARY KEY (id_registro),
    -- IdempotenciaService depende de ella para frenar dos peticiones simultáneas.
    CONSTRAINT uq_idempotencia UNIQUE (id_usuario, operacion, clave),
    CONSTRAINT fk_idempotencia_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT ck_idempotencia_estado CHECK (estado IN ('EN_PROCESO', 'COMPLETADA')),
    CONSTRAINT ck_idempotencia_respuesta CHECK (estado <> 'COMPLETADA' OR codigo_respuesta IS NOT NULL)
);
