    CONSTRAINT fk_conversacion_huesped FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE RESTRICT,
    -- La FK compuesta garantiza que id_anfitrion es el dueño real del alojamiento.
    CONSTRAINT fk_conversacion_alojamiento FOREIGN KEY (id_alojamiento, id_anfitrion)
        REFERENCES alojamiento (id_alojamiento, id_anfitrion) ON DELETE RESTRICT ON UPDATE RESTRICT,
