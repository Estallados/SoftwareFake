-- -----------------------------------------------------------------------------
-- Cotizaciones y reservas (se referencian entre sí: la FK circular va después)
-- -----------------------------------------------------------------------------
CREATE TABLE cotizacion (
    id_cotizacion        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha_entrada        DATE           NOT NULL,
    fecha_salida         DATE           NOT NULL,
    huespedes            INTEGER        NOT NULL,
    noches               INTEGER        NOT NULL,
    -- Precios y porcentajes congelados: son el valor al cotizar, no una copia del catálogo.
    precio_noche         NUMERIC(12, 2) NOT NULL,
    precio_base          NUMERIC(18, 2) NOT NULL,
    descuento            NUMERIC(18, 2) NOT NULL DEFAULT 0,
    porcentaje_limpieza  NUMERIC(5, 2)  NOT NULL,
    valor_limpieza       NUMERIC(18, 2) NOT NULL,
    porcentaje_servicio  NUMERIC(5, 2)  NOT NULL,
    valor_servicio       NUMERIC(18, 2) NOT NULL,
    valor_adicionales    NUMERIC(18, 2) NOT NULL DEFAULT 0,
    total                NUMERIC(18, 2) NOT NULL,
    -- JSON con los servicios elegidos. TEXT y no JSONB: la entidad lo mapea como String.
    desglose             TEXT,
    id_usuario           BIGINT         NOT NULL,
    id_alojamiento       BIGINT         NOT NULL,
    -- Se llena al reservar y vuelve a NULL si el pago falla, para poder reintentar.
    id_reserva           BIGINT,
    fecha_creacion       TIMESTAMP(6)   NOT NULL DEFAULT LOCALTIMESTAMP,
    fecha_expiracion     TIMESTAMP(6)   NOT NULL,
    CONSTRAINT pk_cotizacion PRIMARY KEY (id_cotizacion),
    CONSTRAINT uq_cotizacion_reserva UNIQUE (id_reserva),
    CONSTRAINT fk_cotizacion_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_cotizacion_alojamiento FOREIGN KEY (id_alojamiento)
        REFERENCES alojamiento (id_alojamiento) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_cotizacion_fechas CHECK (fecha_salida > fecha_entrada),
    CONSTRAINT ck_cotizacion_huespedes CHECK (huespedes > 0),
    CONSTRAINT ck_cotizacion_noches CHECK (noches = fecha_salida - fecha_entrada),
    CONSTRAINT ck_cotizacion_vigencia CHECK (fecha_expiracion > fecha_creacion),
    CONSTRAINT ck_cotizacion_porcentajes CHECK (
        porcentaje_limpieza BETWEEN 0 AND 100 AND porcentaje_servicio BETWEEN 0 AND 100),
    CONSTRAINT ck_cotizacion_valores CHECK (
        precio_noche > 0 AND precio_base >= 0 AND descuento >= 0 AND valor_limpieza >= 0
        AND valor_servicio >= 0 AND valor_adicionales >= 0),
    -- Misma fórmula de CotizacionService.calcular.
    CONSTRAINT ck_cotizacion_total CHECK (
        total = precio_base - descuento + valor_limpieza + valor_servicio + valor_adicionales)
);

CREATE TABLE reserva (
    id_reserva      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha_entrada   DATE           NOT NULL,
    fecha_salida    DATE           NOT NULL,
    noches          INTEGER        NOT NULL,
    huespedes       INTEGER        NOT NULL,
    estado          VARCHAR(20)    NOT NULL DEFAULT 'PENDIENTE_PAGO',
    total           NUMERIC(18, 2) NOT NULL,
    desglose        TEXT,
    id_huesped      BIGINT         NOT NULL,
    id_alojamiento  BIGINT         NOT NULL,
    -- Sin UNIQUE: si un pago falla, la misma cotización puede generar otra reserva.
    id_cotizacion   BIGINT         NOT NULL,
    fecha_creacion  TIMESTAMP(6)   NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_reserva PRIMARY KEY (id_reserva),
    -- Destino de la FK compuesta de resena.
    CONSTRAINT uq_reserva_participantes UNIQUE (id_reserva, id_alojamiento, id_huesped),
    CONSTRAINT fk_reserva_huesped FOREIGN KEY (id_huesped)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_reserva_alojamiento FOREIGN KEY (id_alojamiento)
        REFERENCES alojamiento (id_alojamiento) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_reserva_cotizacion FOREIGN KEY (id_cotizacion)
        REFERENCES cotizacion (id_cotizacion) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_reserva_estado CHECK (
        estado IN ('PENDIENTE_PAGO', 'CONFIRMADA', 'EN_REVISION', 'CANCELADA')),
    CONSTRAINT ck_reserva_fechas CHECK (fecha_salida > fecha_entrada),
    CONSTRAINT ck_reserva_noches CHECK (noches = fecha_salida - fecha_entrada),
    CONSTRAINT ck_reserva_huespedes CHECK (huespedes > 0),
    CONSTRAINT ck_reserva_total CHECK (total >= 0)
);
-- Última defensa contra la doble reserva: la primera es el bloqueo de
-- AlojamientoRepository.buscarParaReservar. No incluye PENDIENTE_PAGO porque una
-- pendiente vencida deja de ocupar fechas antes de que el proceso programado la cancele.
ALTER TABLE reserva ADD CONSTRAINT ex_reserva_sin_cruces
    EXCLUDE USING gist (id_alojamiento WITH =, daterange(fecha_entrada, fecha_salida, '[)') WITH &&)
    WHERE (estado IN ('CONFIRMADA', 'EN_REVISION'));

-- FK circular cotizacion <-> reserva: se añade cuando ya existen las dos tablas.
ALTER TABLE cotizacion ADD CONSTRAINT fk_cotizacion_reserva FOREIGN KEY (id_reserva)
    REFERENCES reserva (id_reserva) ON DELETE SET NULL ON UPDATE RESTRICT;

-- -----------------------------------------------------------------------------
-- Pagos, cancelaciones y reseñas
-- -----------------------------------------------------------------------------
CREATE TABLE pago (
    id_pago               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- NULL cuando la pasarela falla antes de entregar una referencia.
    referencia            VARCHAR(255),
    proveedor             VARCHAR(30)    NOT NULL,
    valor                 NUMERIC(18, 2) NOT NULL,
    estado                VARCHAR(20)    NOT NULL,
    detalle               VARCHAR(255),
    fecha                 TIMESTAMP(6)   NOT NULL DEFAULT LOCALTIMESTAMP,
    metodo                VARCHAR(255),
    valor_reembolsado     NUMERIC(18, 2),
    referencia_reembolso  VARCHAR(255),
    id_reserva            BIGINT         NOT NULL,
    CONSTRAINT pk_pago PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva)
        REFERENCES reserva (id_reserva) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_pago_estado CHECK (
        estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'ERROR', 'REEMBOLSADO')),
    CONSTRAINT ck_pago_valor CHECK (valor >= 0),
    CONSTRAINT ck_pago_reembolso CHECK (
        valor_reembolsado IS NULL OR (valor_reembolsado > 0 AND valor_reembolsado <= valor)),
    CONSTRAINT ck_pago_reembolsado CHECK (
        estado <> 'REEMBOLSADO' OR (valor_reembolsado IS NOT NULL AND referencia_reembolso IS NOT NULL))
);

CREATE TABLE cancelacion (
    id_cancelacion         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    motivo                 VARCHAR(500)   NOT NULL,
    -- Nombre de la política aplicada, congelado: la del alojamiento puede cambiar después.
    politica               VARCHAR(50)    NOT NULL,
    porcentaje_reembolso   INTEGER        NOT NULL,
    valor_reembolso        NUMERIC(18, 2) NOT NULL,
    estado                 VARCHAR(20)    NOT NULL,
    estado_final_reserva   VARCHAR(20)    NOT NULL,
    fecha                  TIMESTAMP(6)   NOT NULL DEFAULT LOCALTIMESTAMP,
    id_usuario             BIGINT         NOT NULL,
    id_reserva             BIGINT         NOT NULL,
    CONSTRAINT pk_cancelacion PRIMARY KEY (id_cancelacion),
    -- CancelacionRepository.findByIdReserva espera una sola por reserva.
    CONSTRAINT uq_cancelacion_reserva UNIQUE (id_reserva),
    CONSTRAINT fk_cancelacion_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_cancelacion_reserva FOREIGN KEY (id_reserva)
        REFERENCES reserva (id_reserva) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_cancelacion_estado CHECK (
        estado IN ('SOLICITADA', 'APROBADA', 'RECHAZADA', 'COMPLETADA')),
    CONSTRAINT ck_cancelacion_estado_final CHECK (
        estado_final_reserva IN ('PENDIENTE_PAGO', 'CONFIRMADA', 'EN_REVISION', 'CANCELADA')),
    CONSTRAINT ck_cancelacion_porcentaje CHECK (porcentaje_reembolso BETWEEN 0 AND 100),
    CONSTRAINT ck_cancelacion_valor CHECK (valor_reembolso >= 0),
    CONSTRAINT ck_cancelacion_motivo CHECK (LENGTH(TRIM(motivo)) > 0)
);

CREATE TABLE resena (
    id_resena       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    calificacion    INTEGER       NOT NULL,
    comentario      VARCHAR(2000),
    estado          VARCHAR(20)   NOT NULL DEFAULT 'PUBLICADA',
    fecha           TIMESTAMP(6)  NOT NULL DEFAULT LOCALTIMESTAMP,
    id_usuario      BIGINT        NOT NULL,
    id_reserva      BIGINT        NOT NULL,
    id_alojamiento  BIGINT        NOT NULL,
    CONSTRAINT pk_resena PRIMARY KEY (id_resena),
    -- ResenaService captura esta violación para rechazar una reseña repetida.
    CONSTRAINT uq_resena_reserva UNIQUE (id_reserva),
    -- La FK compuesta garantiza que autor y alojamiento son los de la reserva.
    CONSTRAINT fk_resena_reserva FOREIGN KEY (id_reserva, id_alojamiento, id_usuario)
        REFERENCES reserva (id_reserva, id_alojamiento, id_huesped) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5),
    CONSTRAINT ck_resena_estado CHECK (estado IN ('PUBLICADA', 'OCULTA'))
);

CREATE TABLE favorito (
    id_favorito     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha_agregado  TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
    id_usuario      BIGINT       NOT NULL,
    id_alojamiento  BIGINT       NOT NULL,
    CONSTRAINT pk_favorito PRIMARY KEY (id_favorito),
    -- FavoritoService captura esta violación ante dos peticiones simultáneas.
    CONSTRAINT uq_favorito UNIQUE (id_usuario, id_alojamiento),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_favorito_alojamiento FOREIGN KEY (id_alojamiento)
        REFERENCES alojamiento (id_alojamiento) ON DELETE CASCADE ON UPDATE RESTRICT
);

-- -----------------------------------------------------------------------------
-- Mensajería y notificaciones
